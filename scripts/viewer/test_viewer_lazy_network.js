// The default tree must not wait for the optional CDN-backed network renderer.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('crates/archguard-report/src/viewer.html','utf8');
const harness=fs.readFileSync('scripts/viewer/test_viewer_state.js','utf8').split('const node=(id,name,parent=null,kind=')[0];
const launch=vm.runInNewContext(harness+'\nlaunch;',{require,console,performance,Blob});
const fixture={root:'/tmp/lazy-network',nodes:[{id:0,name:'A',parent:null,kind:'file'},{id:1,name:'B',parent:null,kind:'file'}],edges:[{from:0,to:1,count:1,refs:[]}],findings:[],cyclicEdges:[],view:{depth:0,visible:null}};
assert.doesNotMatch(html,/<script\s+src=/,'the HTML parser must not wait for the optional network CDN before running the application');
const app=launch(fixture,{library:false});
const scripts=()=>app.document.head.children.filter(node=>node.tagName==='SCRIPT');
assert.equal(scripts().length,0,'default tree starts without downloading the network library');
assert.equal(app.ids.get('graph-state').textContent,'','absence of an unused optional library is not a load failure');
assert.ok(app.ids.get('package-tree').querySelectorAll('g[data-tree-source]').length>0);
app.click('diagram-dependencies');assert.equal(scripts().length,0);
app.run("selectNode('A')");
const snapshot=app.run('JSON.stringify([work,view,sccs,currentAcd,ops,ui.selection])');
app.click('diagram-network');
assert.equal(scripts().length,1,'first network selection starts one asynchronous download');
const first=scripts()[0];assert.equal(first.async,true);assert.ok(first.src);
assert.match(app.ids.get('graph-state').textContent,/Loading network/);
app.click('diagram-network');assert.equal(scripts().length,1,'repeated clicks share the pending download');
app.click('diagram-overview');app.run("showTab('calls')");
app.installLibrary();first.onload();
assert.equal(app.run('ui.workspace'),'calls','a late download does not navigate away from the user’s current workspace');
assert.equal(app.run('ui.diagram'),'overview');
assert.equal(app.run('JSON.stringify([work,view,sccs,currentAcd,ops,ui.selection])'),snapshot,'loading preserves graph evidence, scope and selection');
app.run("showTab('graph');setDiagram('network')");
assert.equal(scripts().length,0,'completed download is removed and the available library reused');
assert.equal(app.graph.data.nodes.length,2);
assert.equal(app.ids.get('graph-state').hidden,true);

const failed=launch(fixture,{library:false});
failed.click('diagram-network');
const failedScript=failed.document.head.children[0];failedScript.onerror();
assert.match(failed.ids.get('graph-state').textContent,/could not load/);
let retry=failed.ids.get('graph-state').querySelector('button');assert.ok(retry,'failed download offers an explicit retry');
failed.click('language-de');assert.match(failed.ids.get('graph-state').textContent,/konnte nicht geladen/);assert.match(failed.ids.get('graph-state').querySelector('button').textContent,/Erneut/);
failed.ids.get('graph-state').querySelector('button').click();
assert.equal(failed.document.head.children.length,1);
const retryScript=failed.document.head.children[0];assert.notEqual(retryScript,failedScript);
failedScript.onload();assert.match(failed.ids.get('graph-state').textContent,/geladen/,'stale completion cannot settle the new request');
failed.installLibrary();retryScript.onload();assert.equal(failed.ids.get('graph-state').hidden,true);

const timeout=launch(fixture,{library:false});const timers=[];timeout.context.setTimeout=(fn,delay)=>{timers.push({fn,delay});return timers.length;};
timeout.click('diagram-network');const pending=timeout.document.head.children[0];
assert.ok(timers.some(timer=>timer.delay===15000),'network load has a finite timeout');
timers.find(timer=>timer.delay===15000).fn();
assert.match(timeout.ids.get('graph-state').textContent,/could not load/);assert.equal(timeout.document.head.children.length,0);
timeout.click('diagram-overview');pending.onload();assert.equal(timeout.ids.get('graph-state').hidden,true);
const incomplete=launch(fixture,{library:false});incomplete.click('diagram-network');incomplete.document.head.children[0].onload();assert.match(incomplete.ids.get('graph-state').textContent,/could not load/,'successful HTTP without a ForceGraph export remains a load error');
const existing=launch(fixture);existing.click('diagram-network');assert.equal(existing.document.head.children.length,0,'a preloaded compatible library needs no download');
console.log('Lazy network: offline tree/dependencies, async single load, preserved navigation, localized retry and timeout passed');
