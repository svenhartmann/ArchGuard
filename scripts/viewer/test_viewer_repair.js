// Exercise the complete compare -> confirm -> preview -> undo/export workflow.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const harness=fs.readFileSync('scripts/viewer/test_viewer_state.js','utf8').split('const node=(id,name,parent=null,kind=')[0];
const launch=vm.runInNewContext(harness+'\nlaunch;',{require,console,performance,Blob});
const nodes=['A.ts','B.ts','C.ts'].map((name,id)=>({id,name,kind:'file',parent:null,lang:'ts'}));
const edge=(from,to)=>({from,to,count:1,refs:[{file:nodes[from].name,line:7,raw:'import "<img src=x onerror=alert(1)>";'}]});
const fixture={root:'/tmp/repair',nodes,edges:[edge(0,1),edge(1,0),edge(0,2),edge(2,0)],view:{depth:0,visible:null},findings:[{id:'scc-1',kind:'cycle',nodes:nodes.map(n=>n.name),edge_count:4,suggested_cuts:[]}],cyclicEdges:[]};
const packages=launch({...fixture,nodes:[{id:0,name:'A',kind:'module',parent:null},{id:1,name:'A/a.ts',kind:'file',parent:0},{id:2,name:'B',kind:'module',parent:null},{id:3,name:'B/b.ts',kind:'file',parent:2}],edges:[{from:1,to:3,count:1,refs:[]},{from:3,to:1,count:1,refs:[]}],findings:[]});
packages.run("selectNode('A')");
assert.doesNotMatch(packages.ids.get('module-list').textContent,/Suggested move/,'unvalidated grouping hints no longer dominate the Explorer');
const advanced=packages.ids.get('sidebar').querySelectorAll('details').find(node=>node.className==='expert-simulation');
assert.ok(advanced,'manual grouping remains in an advanced disclosure');
assert.equal(advanced.open,false);
const app=launch(fixture),sidebar=app.ids.get('sidebar');
app.run('focusCycle(cyclesForView()[0])');
const find=(text)=>sidebar.querySelectorAll('button').find(b=>b.textContent===text);
assert.ok(find('Compare solutions'),'a selected cycle offers automatic candidate comparison even without sampled cut suggestions');
const before=app.run('JSON.stringify([data,work,ops])');
find('Compare solutions').click();
assert.ok(sidebar.querySelectorAll('article').length>=2,'comparison offers alternatives');
assert.match(sidebar.textContent,/affected source files/i);
assert.match(sidebar.textContent,/source.*cyclic/i);
assert.match(sidebar.textContent,/not.*minimum|not.*optimal/i,'bounded search does not promise an optimal source refactor');
assert.equal(sidebar.querySelectorAll('img').length,0,'source evidence is rendered safely');
assert.equal(app.run('JSON.stringify([data,work,ops])'),before,'comparing does not change the model');
find('Preview this plan').click();
assert.ok(Array.isArray(app.run('ui.pending')));
assert.equal(app.run('ui.pending.length'),2,'the chosen candidate addresses both cycles');
app.click('cancel-action');
assert.equal(app.run('JSON.stringify([data,work,ops])'),before,'cancel preserves the model');
find('Preview this plan').click();app.click('confirm-action');
assert.equal(app.run('ops.length'),2);assert.equal(app.run('sccs.length'),0);
assert.equal(app.run('JSON.stringify(data)'),JSON.stringify(fixture));
assert.equal(app.run('window.archguardCanReload()'),false);
app.click('undo-ops');
assert.equal(app.run('ops.length'),0,'Undo reverts the complete multi-edit plan in one action');
assert.equal(app.run('findSccs(work).length'),1);
app.run('focusCycle(cyclesForView()[0])');find('Compare solutions').click();
find('Export repair plan').click();
async function verifyExport(){
  const exported=JSON.parse(await app.graph.downloads.at(-1).text());
  assert.equal(exported.schema,'archguard-cycle-repair/v1');
  assert.equal(exported.plan.ops.length,2);
  assert.ok(exported.assumptions.length);
  assert.ok(exported.steps.length);
  app.click('simulation-mode');app.click('simulation-mode');
  app.run("recordOp([encodeCut('A.ts','B.ts'),encodeCut('missing','C.ts')])");
  assert.equal(app.run('ops.length'),0,'a failed batch never applies its valid first edit');
  assert.equal(app.run('findSccs(work).length'),1);
  app.run("recordOp(encodeCut('A.ts','B.ts'));focusCycle(cyclesForView()[0])");
  find('Compare solutions').click();find('Export repair plan').click();
  const dependent=JSON.parse(await app.graph.downloads.at(-1).text());
  assert.equal(dependent.baseOps?.length,1,'export retains the simulation changes on which the new plan depends');
  assert.deepEqual(dependent.sourceGraph.nodes,fixture.nodes,'export identifies the actual original graph snapshot');
  app.context.exportedRepair=dependent;
  const replayed=JSON.parse(app.run('JSON.stringify((()=>{const g=JSON.parse(JSON.stringify(exportedRepair.sourceGraph));for(const op of [...exportedRepair.baseOps,...exportedRepair.plan.ops])applyOp(g,op);return cycleRepairStats(g);})())'));
  assert.deepEqual(replayed,dependent.plan.sourceAfter,'export is reproducible from its source snapshot and complete operation sequence');
  app.click('undo-ops');
  assert.equal(dependent.baseOps.length,1,'exported prerequisite operations are a snapshot');
  console.log('repair workflow: automatic alternatives, evidence, cancel, atomic preview/undo, export and validation passed');
}
verifyExport().catch(error=>{console.error(error);process.exitCode=1;});
