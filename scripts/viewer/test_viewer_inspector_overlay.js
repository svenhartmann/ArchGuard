const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const harness=fs.readFileSync('scripts/viewer/test_viewer_state.js','utf8').split('const node=(id,name,parent=null,kind=')[0];
const launch=vm.runInNewContext(harness+'\nlaunch;',{require,console,performance,Blob});
const fixture={root:'/tmp/details',nodes:['A','B','C'].map((name,id)=>({id,name,kind:'module',parent:null})),edges:[{from:0,to:1,count:1,refs:[]},{from:1,to:0,count:1,refs:[]}],findings:[],cyclicEdges:[],view:{depth:0,visible:null}};
const app=launch(fixture,{library:false}),main=app.ids.get('main'),tree=app.ids.get('package-tree');
const closed=()=>main.classList.contains('inspector-closed');
const control=name=>app.ids.get('inspector').querySelectorAll('button[data-inspector-action]').find(b=>b.getAttribute('data-inspector-action')===name);
const key=(key,target=tree)=>{for(const handler of app.document.events.keydown)handler({key,target,preventDefault(){},stopPropagation(){}});};
assert.equal(closed(),true,'Details start closed on desktop');
assert.equal(main.classList.contains('inspector-pinned'),false);
assert.equal(main.style['--inspector-width'],'420px');
app.run("selectNode('A')");
assert.equal(closed(),true,'selection only highlights the graph');
assert.notEqual(app.document.activeElement,app.ids.get('sidebar'),'selection must not move focus into hidden details');
app.run("ui.edgeMode='incoming';treeZoom=1.5");tree.scrollTop=110;tree.scrollLeft=70;
const state=()=>app.run('JSON.stringify([ui.selection,ui.edgeMode,treeZoom,work,view,ops])')+JSON.stringify([tree.scrollTop,tree.scrollLeft]);
const before=state(),svg=tree.querySelector('svg');
app.click('toggle-inspector');
assert.equal(closed(),false);
assert.equal(app.ids.get('inspector').getAttribute('aria-modal'),'false');
assert.match(app.ids.get('sidebar').textContent,/A/);
assert.equal(tree.querySelector('svg'),svg,'opening an overlay must not rebuild the diagram');
assert.equal(state(),before);
const metric=app.ids.get('sidebar').querySelector('div[data-metric-help]');assert.ok(metric);metric.dispatch('focus');
assert.equal(app.ids.get('metric-tooltip').hidden,false);key('Escape');
// Escape closes the topmost layer first: the tooltip, then the details.
assert.equal(app.ids.get('metric-tooltip').hidden,true);assert.equal(closed(),false,'the first Escape only hides the tooltip');key('Escape');
assert.equal(closed(),true);assert.equal(state(),before,'Escape closes details without changing selection, directions or viewport');
app.click('toggle-inspector');control('close').click();assert.equal(state(),before);
app.run("selectEdge(view.edges[0])");assert.equal(closed(),true,'connections also select without opening');
app.click('toggle-inspector');app.run("selectNode('B')");
assert.equal(closed(),false);assert.match(app.ids.get('sidebar').querySelector('h2').textContent,/B/,'an open drawer follows selection');
app.click('language-de');assert.equal(app.ids.get('toggle-inspector').textContent,'Details');assert.equal(control('pin').textContent,'Anheften');
control('pin').click();assert.equal(main.classList.contains('inspector-pinned'),true);assert.equal(control('pin').getAttribute('aria-pressed'),'true');
control('pin').click();assert.equal(main.classList.contains('inspector-pinned'),false);
control('close').click();
const rows=()=>tree.querySelectorAll('g[data-tree-source]');
const b=rows().find(n=>n.getAttribute('data-tree-source')==='1');assert.ok(b);
b.dispatch('keydown',{key:'Enter'});assert.equal(closed(),false);assert.equal(app.run('ui.selection.name'),'B');
control('close').click();
rows().find(n=>n.getAttribute('data-tree-source')==='0').dispatch('keydown',{key:' '});
assert.equal(closed(),true,'Space selects without opening');
key('Enter',app.ids.get('filter'));assert.equal(closed(),true,'typing in controls must not open Details');
key('Enter',tree);assert.equal(closed(),false,'Enter on the diagram opens the current selection');
control('close').click();
app.run("ui.pending={kind:'test'}");app.ids.get('action-dialog').open=true;app.click('toggle-inspector');key('Escape');
assert.equal(closed(),false,'a modal owns Escape before the drawer');app.ids.get('action-dialog').open=false;
app.run("ui.pending=null");control('close').click();
const small=launch(fixture,{library:false,width:390});small.run("selectNode('A')");assert.equal(small.ids.get('main').classList.contains('inspector-closed'),true);
small.click('toggle-inspector');assert.equal(small.ids.get('main').style['--inspector-width'],'342px');
assert.equal(small.ids.get('inspector').querySelectorAll('button[data-inspector-action]').find(b=>b.getAttribute('data-inspector-action')==='pin').disabled,true,'pinning is only offered where a separate column fits');
console.log('Details overlay: explicit open, live selection, Escape/close state preservation, pinning, keyboard, focus, DE/EN and compact bounds passed');

const network=launch(fixture);network.run("setDiagram('network');selectNode('A');fg.zoom(1.7);fg.centerAt(120,80,0)");
const camera=JSON.stringify([network.graph.zoom,network.graph.centers,network.graph.fits,network.graph.updates]);
network.click('toggle-inspector');network.ids.get('inspector').querySelectorAll('button[data-inspector-action]').find(b=>b.getAttribute('data-inspector-action')==='close').click();
assert.equal(JSON.stringify([network.graph.zoom,network.graph.centers,network.graph.fits,network.graph.updates]),camera,'the network camera is also unchanged by overlay toggles');
