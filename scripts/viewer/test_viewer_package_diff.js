'use strict';
const assert=require('node:assert/strict');
const {prepareDiffView,filterDiffCycles}=require('../crates/archguard-report/src/viewer_package_diff.js');
const n=(id,name,parent=null,kind='module')=>({id,name,parent,kind});
const nodes=[n(0,'app'),n(1,'app/client',0),n(2,'app/search',0),n(3,'app/util',0),n(10,'app/client/A.ts',1,'file'),n(11,'app/client/B.ts',1,'file'),n(20,'app/search/S.ts',2,'file'),n(30,'app/util/U.ts',3,'file'),n(40,'root.ts',null,'file')];
const edge=(from,to,line=1,count=1)=>({from,to,count,refs:[{file:nodes.find(n=>n.id===from).name,line,raw:`import ${to}`} ]});
const graph=edges=>({nodes,edges});
const original={base_graph:graph([edge(10,20),edge(11,20,2,3),edge(20,30),edge(10,11)]),target_graph:graph([edge(10,20),edge(11,20,2,3),edge(20,10),edge(20,30),edge(10,11)])};
const frozen=JSON.stringify(original);
const collisionNodes=[n(0,'(Projektwurzel)'),n(1,'(Projektwurzel)/A.ts',0,'file'),n(2,'root.ts',null,'file')];
const collision=prepareDiffView({base_graph:{nodes:collisionNodes,edges:[]},target_graph:{nodes:collisionNodes,edges:[]}},'packages');
assert.equal(new Set(collision.target_graph.nodes.map(n=>n.name)).size,2,'root files must not collide with a real package sharing a display label');
let view=prepareDiffView(original,'packages','direct');
assert.deepEqual(view.base_graph.nodes.map(n=>n.name),['/','app/client','app/search','app/util']);
assert.equal(view.base_graph.edges.length,2,'internal class/file edges do not become package self-cycles');
const names=g=>new Map(g.nodes.map(n=>[n.id,n.name]));
const pairs=g=>g.edges.map(e=>[names(g).get(e.from),names(g).get(e.to)]);
const client=view.base_graph.edges.find(e=>names(view.base_graph).get(e.from)==='app/client');
assert.equal(client.count,4);assert.equal(client.refs.length,2,'all contributing source evidence is kept');
assert.deepEqual(view.added_edges.map(e=>[e.from,e.to]),[['app/search','app/client']]);
assert.equal(view.changed_edges.length,0,'an unchanged dependency becoming cyclic is a cycle change, not changed evidence');
assert.equal(view.cycle_changes.added_edges.length,2,'includes the unchanged forward edge in the new cycle');
assert.equal(view.cycle_changes.removed_edges.length,0);
let cyclic=filterDiffCycles(view,'cycles');
assert.deepEqual(pairs(cyclic.base_graph),[]);
assert.deepEqual(pairs(cyclic.target_graph),[['app/client','app/search'],['app/search','app/client']]);
assert.equal(cyclic.target_graph.nodes.length,2,'non-cyclic neighbors do not clutter cycle-only view');
let acyclic=filterDiffCycles(view,'acyclic');
assert.equal(acyclic.base_graph.edges.length,2);
assert.deepEqual(pairs(acyclic.target_graph),[['app/search','app/util']],'an outgoing bridge from a cyclic package is not a cycle edge');
assert.equal(acyclic.added_edges.length,1,'filters retain the underlying diff classifications');
assert.deepEqual(pairs(prepareDiffView(original,'packages',0).target_graph),[],'a coarser package level recomputes cycles instead of carrying hidden internal cycles');
const reverse=prepareDiffView({base_graph:original.target_graph,target_graph:original.base_graph},'packages','direct');
assert.equal(reverse.cycle_changes.removed_edges.length,2);
const evidenceOnly=prepareDiffView({base_graph:graph([edge(10,20)]),target_graph:graph([edge(11,20)])},'packages','direct');
assert.equal(evidenceOnly.added_edges.length,0);assert.equal(evidenceOnly.removed_edges.length,0);assert.equal(evidenceOnly.changed_edges.length,1);
const unknown=prepareDiffView({base_graph:graph([edge(10,20,1,null)]),target_graph:graph([edge(10,20,1,null)])},'packages','direct');
assert.equal(unknown.target_graph.edges[0].count,null,'missing counts remain unknown');
const noFileCycle={base_graph:graph([edge(10,20)]),target_graph:graph([edge(10,20),edge(20,11)])};
assert.equal(prepareDiffView(noFileCycle,'files').cycle_changes.added_edges.length,0);
assert.equal(prepareDiffView(noFileCycle,'packages','direct').cycle_changes.added_edges.length,2,'package cycles do not require the same classes to form a closed path');
assert.equal(JSON.stringify(original),frozen,'projection/filtering do not mutate the source snapshots');
const largeNodes=Array.from({length:12000},(_,i)=>n(i,'p'+i,null,'file'));
const largeEdges=largeNodes.map((_,i)=>({from:i,to:(i+1)%12000,count:1,refs:[]}));
const large=prepareDiffView({base_graph:{nodes:largeNodes,edges:[]},target_graph:{nodes:largeNodes,edges:largeEdges}},'files');
assert.equal(large.cycle_changes.added_edges.length,12000,'cycle detection is stack-safe on deep graphs');
console.log('Package diff: aggregation, exact counts/evidence, independent cycle membership, bridges, depth, file/package distinction and 12k-node cycles passed');
