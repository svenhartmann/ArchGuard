// Manifest projects remain distinct from deployments and from runtime connections.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const harness=fs.readFileSync('scripts/viewer/test_viewer_state.js','utf8').split('const node=(id,name,parent=null,kind=')[0];
const launch=vm.runInNewContext(harness+'\nlaunch;',{require,console,performance,Blob});
const project=(path,kind='application',name='search')=>({id:'project:'+path+'/pom.xml',name,path,manifest:path+'/pom.xml',ecosystem:'maven',kind,runtime:kind==='application'?'azure-functions':null,evidence:[{file:path+'/pom.xml',line:42,pointer:'/project/build/plugins/plugin',description:'Declared Azure Functions plugin <img src=x onerror=alert(1)>'}]});
const projects=[project('functions/search'),project('functions/import'),project('tests/browser','tooling','browser-tests'),project('shared/core','library','shared-core')];
const service=p=>({id:p.id,name:p.name,project:p.id,compose_file:'',build_context:p.path,networks:[],profiles:[]});
const apps=projects.filter(p=>p.kind==='application').map(service);
const topology={schema_version:1,root:'/repo',monorepo:true,monorepo_reason:'Four manifest projects',complete:true,projects,compose_files:[],services:apps,dependencies:[],cycles:[],diagnostics:[]};
const fixture={root:'/repo',nodes:[{id:0,name:'src/A.java',kind:'file',parent:null}],edges:[],findings:[],cyclicEdges:[],view:{depth:0,visible:null},services:topology};
const app=launch(fixture,{library:false});app.run("showTab('services')");
const tree=()=>app.ids.get('services-tree'),nodes=()=>tree().querySelectorAll('g[data-service-node]');
assert.equal(nodes().length,2,'manifest applications must be visible even when no Compose file exists');
assert.deepEqual(Array.from(nodes(),n=>n.getAttribute('data-service-node')).sort(),apps.map(s=>s.id).sort(),'same artifact names in different project directories retain identity');
assert.match(tree().textContent,/functions\/search/);assert.match(tree().textContent,/functions\/import/);
assert.doesNotMatch(nodes()[0].textContent,/Networks:|Local build context:/,'manifest application tooltips do not imply Compose network/build declarations');
assert.equal(tree().querySelectorAll('g[data-service-edge]').length,0,'equal names and shared technology cannot invent service connections');
assert.match(app.ids.get('services-status').textContent,/2 applications.*0 containers/);
const inventory=()=>app.ids.get('services-project-list').querySelectorAll('button[data-service-project]');
assert.equal(inventory().length,4,'tooling and libraries belong in project inventory, not service nodes');
const choose=id=>inventory().find(b=>b.getAttribute('data-service-project')===id).click();
const snapshot=app.run('JSON.stringify([data.nodes,data.edges,data.services,work,ops])');
choose(projects[0].id);
assert.equal(app.run('serviceUi.selected'),apps[0].id);
assert.match(app.ids.get('sidebar').textContent,/Project path: functions\/search/);
assert.match(app.ids.get('sidebar').textContent,/azure-functions/);
assert.match(app.ids.get('sidebar').textContent,/pom.xml:42/);
assert.match(app.ids.get('sidebar').textContent,/no.*connections.*found/i);
assert.doesNotMatch(app.ids.get('sidebar').textContent,/Compose service/);
assert.equal(app.ids.get('sidebar').querySelectorAll('img').length,0);
choose(projects[2].id);
assert.equal(app.run('serviceUi.selected'),null,'tooling selection must not borrow an application reference');
assert.match(app.ids.get('sidebar').textContent,/Test.*tool|Tooling/i);
assert.match(app.ids.get('sidebar').textContent,/tests\/browser/);
assert.equal(nodes().length,2);
assert.equal(app.ids.get('services-direction').disabled,true);
app.run("setViewerLanguage('de')");
assert.equal(app.run('serviceUi.project'),projects[2].id);
assert.match(app.ids.get('sidebar').textContent,/Projektpfad: tests\/browser/);
assert.match(app.ids.get('services-projects-summary').textContent,/4 Projekte/);
app.run("setViewerLanguage('en')");
const exportData=JSON.parse(app.run('JSON.stringify(exportSnapshot())'));
assert.deepEqual(exportData.projects,projects,'export includes the complete inventory, not only service applications');
assert.equal(exportData.monorepo,true);assert.equal(exportData.monorepo_reason,topology.monorepo_reason);
assert.equal(exportData.nodes.length,2);
const markdown=app.run('exportMarkdown(exportSnapshot())');
assert.match(markdown,/Project inventory/);assert.match(markdown,/tests\/browser\/pom.xml/);assert.match(markdown,/shared\/core/);
assert.match(markdown,/pom.xml:42/);assert.ok(!markdown.includes('<img'),'project evidence is escaped in Markdown');
assert.equal(app.run('JSON.stringify([data.nodes,data.edges,data.services,work,ops])'),snapshot,'service inventory and exports leave source analysis unchanged');

const container={id:'local/compose.yml::elastic',name:'elasticsearch',compose_file:'local/compose.yml',build_context:null,networks:['default'],profiles:[]};
const mixed=launch({...fixture,services:{...topology,compose_files:['local/compose.yml'],services:[...apps,container]}},{library:false});mixed.run("showTab('services')");
assert.equal(mixed.ids.get('services-tree').querySelectorAll('g[data-service-node]').length,3);
assert.match(mixed.ids.get('services-status').textContent,/2 applications.*1 containers/);
assert.match(mixed.ids.get('services-tree').textContent,/local\/compose.yml/);
mixed.ids.get('services-tree').querySelectorAll('g[data-service-node]').find(n=>n.getAttribute('data-service-node')===container.id).click();
assert.match(mixed.ids.get('sidebar').textContent,/Compose service.*local\/compose.yml/);

const many=Array.from({length:105},(_,i)=>project('tools/'+String(i).padStart(3,'0'),'tooling','tool-'+i));
const large=launch({...fixture,services:{...topology,projects:many,services:[]}},{library:false});large.run("showTab('services')");
const largeRows=()=>large.ids.get('services-project-list').querySelectorAll('button[data-service-project]');
assert.equal(largeRows().length,100,'project inventory renders bounded pages');
large.ids.get('services-project-more').focus();large.click('services-project-more');
assert.equal(largeRows().length,105);assert.equal(large.ids.get('services-project-more').hidden,true);
assert.equal(large.document.activeElement,largeRows()[100],'last-page pagination moves focus to its first new record');
const last=largeRows()[104];last.focus();last.click();
assert.equal(large.document.activeElement.getAttribute('data-service-project'),many[104].id,'project inspection retains keyboard focus');
assert.equal(large.ids.get('services-tree').querySelectorAll('g[data-service-node]').length,0,'tool-only repositories do not fabricate services');
assert.match(large.ids.get('services-status').textContent,/105 projects/);
assert.equal(JSON.parse(large.run('JSON.stringify(exportSnapshot())')).projects.length,105,'all projects are exported irrespective of page bounds');
console.log('Monorepo: manifest applications without Compose, distinct project identity, deployment grouping, honest inventory, evidence, bounded focus, DE/EN and exports passed');
