'use strict';
const assert = require('node:assert/strict');
const { buildDiffRows, visibleDiffEdges, diffLabels } = require('../../crates/archguard-report/src/viewer_staged_diff.js');
const node=(id,name,parent=null,kind='file')=>({id,name,parent,kind});
const report={base_graph:{nodes:[node(0,'pkg',null,'module'),node(1,'pkg/a.ts',0),node(2,'pkg/b.ts',0)],edges:[{from:1,to:2,refs:[]}]},staged_graph:{nodes:[node(8,'pkg',null,'module'),node(9,'pkg/a.ts',8),node(10,'pkg/b.ts',8),node(11,'pkg/c.ts',8)],edges:[{from:9,to:10,refs:[]},{from:10,to:11,refs:[]}]},added_nodes:['pkg/c.ts'],removed_nodes:[],added_edges:[{from:'pkg/b.ts',to:'pkg/c.ts'}],removed_edges:[],changed_edges:[]};
let rows=buildDiffRows(report,new Set(),true,'');
assert.deepEqual(rows.map(r=>r.name),['pkg']);
rows=buildDiffRows(report,new Set(['pkg']),true,'');
assert.deepEqual(rows.map(r=>r.name),['pkg','pkg/a.ts','pkg/b.ts','pkg/c.ts']);
assert.equal(rows.find(r=>r.name==='pkg/c.ts').before,false);
assert.equal(rows.find(r=>r.name==='pkg/c.ts').after,true);
let links=visibleDiffEdges(report,'staged_graph',rows);
assert.deepEqual(links.map(e=>[e.from,e.to,e.change]),[['pkg/a.ts','pkg/b.ts','unchanged'],['pkg/b.ts','pkg/c.ts','added']]);
assert.deepEqual(visibleDiffEdges(report,'base_graph',buildDiffRows(report,new Set(),true,'')),[]);
assert.deepEqual(buildDiffRows(report,new Set(['pkg']),true,'c.ts').map(r=>r.name),['pkg','pkg/c.ts']);
console.log('staged architecture layout: shared identity, hierarchy, context and edge direction verified');
const branch={...report,target:'ref',base_ref:'main',target_ref:'feature/architecture',target_graph:report.staged_graph};
delete branch.staged_graph;
const branchRows=buildDiffRows(branch,new Set(['pkg']),true,'');
assert.deepEqual(branchRows,buildDiffRows(report,new Set(['pkg']),true,''));
assert.deepEqual(visibleDiffEdges(branch,'target_graph',branchRows),links);
const branchLabels=diffLabels({...branch,base_commit:'abc123',target_commit:'def456',policy_source:'target'});
assert.equal(branchLabels.target,'feature/architecture');
assert.match(branchLabels.revision,/main \(abc123\) → feature\/architecture \(def456\)/);
assert.match(branchLabels.explanation,/Branch-Spitzen/);
assert.doesNotMatch(branchLabels.heading,/Staging/);
const indexLabels=diffLabels({target:'index',base_ref:'HEAD',base_commit:'abc123',index_fingerprint:'def456',policy_source:'index'});
assert.equal(indexLabels.target,'Git-Index · gestagt');
assert.match(indexLabels.explanation,/teilweise gestagte/);
console.log('branch architecture layout: commit snapshots share the staged layout and directed evidence');
