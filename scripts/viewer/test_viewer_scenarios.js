// Persisted graph experiments are explicit, portable and transactional.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const harness=fs.readFileSync('scripts/viewer/test_viewer_state.js','utf8').split('const node=(id,name,parent=null,kind=')[0]
  .replace('document,window,navigator:{},localStorage:',"document,window,navigator:{},crypto:require('node:crypto').webcrypto,TextEncoder,localStorage:");
const launch=vm.runInNewContext(harness+'\nlaunch;',{require,console,performance,Blob,TextEncoder});
const storageValues=new Map(),storage={getItem:key=>storageValues.get(key)||null,setItem:(key,value)=>storageValues.set(key,value)};
const node=(id,name,parent=null,kind='file')=>({id,name,parent,kind,lang:'ts'});
const fixture={root:'/projects/first',nodes:[node(0,'app',null,'module'),node(1,'app/A.ts',0),node(2,'domain',null,'module'),node(3,'domain/B.ts',2)],edges:[{from:1,to:3,count:1,refs:[{file:'app/A.ts',line:4,raw:'import B'}]},{from:3,to:1,count:1,refs:[{file:'domain/B.ts',line:2,raw:'import A'}]}],view:{depth:0,visible:null},findings:[],cyclicEdges:[]};
const copy=value=>JSON.parse(JSON.stringify(value));
async function main(){
  const app=launch(fixture,{storage});
  assert.equal(app.run('typeof scenarioSnapshot'),'function','named scenario persistence is available');
  app.run("setSimulation(true); recordOp(encodeCut('app','domain'))");
  const before=app.run('JSON.stringify([data,work,ops,view.nodes.map(n=>n.name)])');
  const snapshot=await app.run("scenarioSnapshot('Break cycle','Review an adapter boundary')");
  assert.equal(snapshot.schema,'archguard-refactoring-scenario/v1');
  assert.equal(snapshot.project,fixture.root);
  assert.match(snapshot.source.fingerprint,/^sha256:[a-f0-9]{64}$/);
  const renumbered=copy(fixture);renumbered.nodes=renumbered.nodes.map(node=>({...node,id:node.id+20,parent:node.parent===null?null:node.parent+20})).reverse();renumbered.edges=renumbered.edges.map(edge=>({...edge,from:edge.from+20,to:edge.to+20})).reverse();
  const reindexed=launch(renumbered,{storage});
  assert.equal((await reindexed.run('scenarioSource()')).fingerprint,snapshot.source.fingerprint,'source identity ignores volatile node IDs and ordering');
  assert.deepEqual(copy(snapshot.ops),[{cut_edge:{from:'app',to:'domain'}}]);
  assert.deepEqual(copy(snapshot.scope.nodes),['app','domain']);
  assert.equal(app.run('JSON.stringify([data,work,ops,view.nodes.map(n=>n.name)])'),before);
  assert.equal(JSON.stringify(await app.run("scenarioSnapshot('Break cycle','Review an adapter boundary')")),JSON.stringify(snapshot),'same scenario exports deterministically without volatile timestamps');
  app.ids.get('scenario-name').value='Break cycle';app.ids.get('scenario-description').value='Review an adapter boundary';
  await app.run('scenarioSaveCurrent()');
  assert.equal(app.run('scenarioReadStore().items.length'),1);
  const fresh=launch(fixture,{storage});
  assert.equal(fresh.run('ops.length'),0,'saved experiments never auto-replay on startup');
  assert.equal(fresh.run('scenarioReadStore().items.length'),1,'same project reload recovers its named scenarios');
  const foreign=launch({...fixture,root:'/projects/second'},{storage});
  assert.equal(foreign.run('scenarioReadStore().items.length'),0,'a different project with the same nodes does not share storage');
  const sameBase=launch({...fixture,root:'/elsewhere/first'},{storage});
  assert.equal(sameBase.run('scenarioReadStore().items.length'),0,'same basename is not project identity');
  fresh.context.doc=copy(snapshot);
  await fresh.run('scenarioRequestLoad(doc)');
  assert.equal(fresh.run('ops.length'),0,'load waits for a concrete confirmation');
  assert.match(fresh.ids.get('action-description').textContent,/Break cycle/);
  assert.equal(fresh.run('confirmScenarioAction()'),true);
  assert.equal(fresh.run('ops.length'),1);
  assert.equal(fresh.run('work.edges.length'),1);
  const current=fresh.run('JSON.stringify([work,ops])');
  fresh.context.bad={...copy(snapshot),ops:[{cut_edge:{from:'app',to:'domain'}},{move_node:{node:'missing',new_parent:'domain'}}]};
  assert.equal(await fresh.run('scenarioRequestLoad(bad)'),false);
  assert.equal(fresh.run('JSON.stringify([work,ops])'),current,'invalid later edit cannot apply an earlier valid operation');
  fresh.context.bad={...copy(snapshot),scope:{nodes:['absent/package']}};
  assert.equal(await fresh.run('scenarioRequestLoad(bad)'),false);
  assert.equal(fresh.run('JSON.stringify([work,ops])'),current,'missing saved cut node preserves the active graph');
  fresh.context.bad={...copy(snapshot),scope:{nodes:['app','app/A.ts']}};
  assert.equal(await fresh.run('scenarioRequestLoad(bad)'),false,'overlapping saved cut is rejected');
  fresh.context.bad={...copy(snapshot),ops:[{cut_edge:{from:'app',to:'domain',extra:true}}]};
  assert.equal(await fresh.run('scenarioRequestLoad(bad)'),false,'unknown operation fields are rejected');
  for(const invalid of ['null','[]','{"schema":"unknown"}',JSON.stringify({...copy(snapshot),schema:'archguard-refactoring-scenario/v99'}),' '.repeat(1024*1024+1)]){
    fresh.context.invalid=invalid;
    assert.equal(await fresh.run('scenarioImportText(invalid)'),false);
    assert.equal(fresh.run('JSON.stringify([work,ops])'),current);
  }
  const changed=copy(fixture);changed.edges[0].refs[0].line=9;
  const stale=launch(changed,{storage});stale.context.doc=copy(snapshot);
  await stale.run('scenarioRequestLoad(doc)');
  assert.match(stale.ids.get('action-description').textContent,/changed|different/i,'stale graph evidence requires an explicit warning');
  assert.equal(stale.run('ops.length'),0);
  stale.run('cancelScenarioAction(); closeDialog()');
  assert.equal(stale.run('ops.length'),0);
  foreign.context.imported=JSON.stringify(snapshot);
  await foreign.run('scenarioImportText(imported)');
  assert.match(foreign.ids.get('action-description').textContent,/different project|another project/i);
  assert.equal(foreign.run('ops.length'),0);
  foreign.run('confirmScenarioAction()');
  assert.equal(foreign.run('ops.length'),1,'explicit adoption replays portable names in another checkout');
  assert.equal(foreign.run('scenarioReadStore().items.length'),0,'import preview is not silently persisted');
  const expanded=launch(fixture,{storage});expanded.run("expandNode('app');setSimulation(true);recordOp(encodeCut('app','domain'))");
  const deep=await expanded.run("scenarioSnapshot('Package review','')");
  assert.deepEqual(copy(deep.scope.nodes),['app/A.ts','domain']);
  const shallow=launch(fixture,{storage});shallow.context.doc=copy(deep);
  shallow.run("selectNode('domain')");
  await shallow.run('scenarioRequestLoad(doc)');
  shallow.click('confirm-action');
  assert.equal(shallow.run('ops.length'),1,'the shared confirmation button commits a scenario replacement');
  assert.deepEqual(copy(shallow.run('view.nodes.map(node=>node.name).sort()')),copy(deep.scope.nodes),'loading restores the saved cut even when the report starts at another depth');
  assert.equal(shallow.run('ui.selection.name'),'domain','a valid selection survives scenario loading');
  shallow.click('undo-ops');
  assert.equal(shallow.run('ops.length'),0,'loaded scenario edits undo as one batch');
  shallow.click('scenario-open');
  assert.equal(shallow.run('window.archguardCanReload()'),false,'an open scenario editor blocks automatic live reload');
  for(const handler of shallow.document.events.keydown||[])handler({key:'Escape',preventDefault(){}});
  assert.equal(shallow.run('ui.selection?.name'),'domain','Escape in the scenario editor must not clear the graph selection');
  shallow.click('scenario-close');
  assert.equal(shallow.run('window.archguardCanReload()'),true);
  fresh.ids.get('scenario-name').value='Break cycle';fresh.ids.get('scenario-description').value='Replacement';
  await fresh.run('scenarioSaveCurrent()');
  assert.match(fresh.ids.get('action-description').textContent,/replace|overwrite/i);
  fresh.run('cancelScenarioAction(); closeDialog()');
  assert.equal(fresh.run('scenarioReadStore().items[0].description'),'Review an adapter boundary','cancelled overwrite preserves persisted data');
  await fresh.run('scenarioSaveCurrent()');
  const parallel=launch(fixture,{storage});parallel.ids.get('scenario-name').value='From another tab';
  await parallel.run('scenarioSaveCurrent()');
  fresh.run('confirmScenarioAction()');
  assert.deepEqual(copy(fresh.run('scenarioReadStore().items.map(item=>item.name)')),['Break cycle','From another tab'],'confirming overwrite must preserve scenarios saved meanwhile in another tab');
  fresh.ids.get('scenario-list').value='From another tab';fresh.run('scenarioDeleteSelected()');
  fresh.run('cancelScenarioAction(); closeDialog()');
  assert.equal(fresh.run('scenarioReadStore().items.length'),2,'cancelled deletion keeps both records');
  fresh.run('scenarioDeleteSelected();confirmScenarioAction()');
  assert.equal(fresh.run('scenarioReadStore().items.length'),1);
  const quota=launch(fixture,{storage:{getItem(){return null;},setItem(){throw Error('Quota exceeded');}}});
  quota.ids.get('scenario-name').value='Quota';assert.equal(await quota.run('scenarioSaveCurrent()'),false);
  assert.match(quota.ids.get('scenario-status').textContent,/Quota exceeded/,'quota errors are visible and are not reported as saved');
  const corruptValues=new Map(),corruptStorage={getItem:key=>corruptValues.get(key)||null,setItem:(key,value)=>corruptValues.set(key,value)};
  const corrupt=launch(fixture,{storage:corruptStorage});const corruptKey=corrupt.run('scenarioStorageKey()');corruptValues.set(corruptKey,'not JSON');corrupt.ids.get('scenario-name').value='Do not replace broken data';
  assert.equal(await corrupt.run('scenarioSaveCurrent()'),false);
  assert.equal(corruptValues.get(corruptKey),'not JSON','invalid persisted data is never silently reset while saving');
  const competing={...copy(snapshot),name:'Concurrent name',description:'Other tab content'};
  let racedValue=null,raceArmed=false,raceReads=0;
  const racingStorage={getItem(key){if(!key.startsWith('archguard-scenarios/'))return null;if(raceArmed&&++raceReads===2)racedValue=JSON.stringify([competing]);return racedValue;},setItem(key,value){if(key.startsWith('archguard-scenarios/'))racedValue=value;}};
  const racing=launch(fixture,{storage:racingStorage});racing.ids.get('scenario-name').value='Concurrent name';racing.ids.get('scenario-description').value='Current tab content';await racing.run('scenarioSource()');raceArmed=true;
  await racing.run('scenarioSaveCurrent()');
  assert.equal(JSON.parse(racedValue)[0].description,'Other tab content','a newly appearing same-name scenario must not be overwritten without confirmation');
  assert.equal(racing.run('!!scenarioPending'),true);
  racing.click('cancel-action');assert.equal(JSON.parse(racedValue)[0].description,'Other tab content');
  await racing.run('scenarioSaveCurrent()');
  racedValue=JSON.stringify([{...competing,description:'Updated again during confirmation'}]);
  racing.click('confirm-action');
  assert.equal(JSON.parse(racedValue)[0].description,'Updated again during confirmation','confirmation applies only to the reviewed saved version');
  assert.equal(racing.run('!!scenarioPending'),true,'a changed saved version requires a fresh confirmation');
  racing.click('confirm-action');assert.equal(JSON.parse(racedValue)[0].description,'Current tab content');
  const moved=launch(fixture);moved.run("setSimulation(true);recordOp(encodeMove('app/A.ts','domain'));expandNode('domain')");
  const movedDocument=await moved.run("scenarioSnapshot('Move and inspect','')");
  const undoMove=launch(fixture);undoMove.context.doc=copy(movedDocument);await undoMove.run('scenarioRequestLoad(doc)');undoMove.click('confirm-action');
  assert.deepEqual(copy(undoMove.run('view.nodes.map(node=>node.name).sort()')),['app','domain/A.ts','domain/B.ts']);
  undoMove.click('undo-ops');
  assert.equal(undoMove.run('[...visible].filter(id=>ancestorsOf(work,id).some(parent=>visible.has(parent))).length'),0,'undo normalizes a post-move saved cut so a parent and child never count separately');
  assert.deepEqual(copy(undoMove.run('view.nodes.map(node=>node.name).sort()')),['app','domain/B.ts']);
  assert.deepEqual(copy(undoMove.run('work.nodes.filter(node=>node.kind===\'file\'&&nearestVisible(work,visible,node.id)!==undefined).map(node=>node.name).sort()')),['app/A.ts','domain/B.ts'],'normalizing the cut preserves both source files through their visible representatives');
  assert.equal(undoMove.run('view.edges.length'),2,'both dependency directions remain represented after undo');
  assert.equal(undoMove.run('view.nodes.length'),2);assert.equal(undoMove.run('currentAcd'),2);assert.equal(undoMove.run('sccs.length'),1,'cycle and ACD use the normalized two-node scope');
  const denied=launch(fixture);denied.run("setSimulation(true);recordOp(encodeCut('app','domain'))");
  denied.ids.get('scenario-name').value='Offline';
  assert.equal(await denied.run('scenarioSaveCurrent()'),false);
  assert.match(denied.ids.get('scenario-status').textContent,/storage|Storage/);
  await denied.run('scenarioExportCurrent()');
  const exported=JSON.parse(await denied.graph.downloads.at(-1).text());
  assert.equal(exported.name,'Offline','JSON export works even when local persistence is blocked');
  assert.equal(exported.ops.length,1);
  denied.click('language-de');denied.click('scenario-open');
  assert.match(denied.ids.get('scenario-status').textContent,/Speicher/);
  assert.equal(denied.run('ops.length'),1,'language changes do not edit a scenario');
  console.log('Scenarios: deterministic named snapshots, project isolation, explicit stale/foreign replay, atomic validation, persistence, safe imports and storage fallback passed');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
