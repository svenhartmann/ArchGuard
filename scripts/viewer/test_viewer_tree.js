// Main package diagram: a scrollable containment tree with real import arrows.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const harness=fs.readFileSync('scripts/viewer/test_viewer_state.js','utf8').split('const node=(id,name,parent=null,kind=')[0];
const launch=vm.runInNewContext(harness+'\nlaunch;',{require,console,performance,Blob});
const node=(id,name,parent=null,kind='module')=>({id,name,parent,kind,lang:'ts'});
const edge=(from,to,count=1)=>({from,to,count,refs:[{file:'A/a.ts',line:7,raw:'import "<img src=x onerror=alert(1)>";'}]});
const fixture={root:'/tmp/tree',nodes:[node(0,'A'),node(1,'A/a.ts',0,'file'),node(2,'A/end.ts',0,'file'),node(3,'B'),node(4,'B/b.ts',3,'file'),node(5,'C'),node(6,'C/c.ts',5,'file')],edges:[edge(1,4,25),edge(4,1,2),edge(4,6),edge(6,2)],view:{depth:0,visible:null},findings:[],cyclicEdges:[]};
const app=launch(fixture);
assert.ok(app.ids.has('package-tree'),'the main diagram needs a package tree with directed edges');
const tree=a=>a.ids.get('package-tree');
const pairs=a=>Array.from(tree(a).querySelectorAll('g[data-tree-edge]'),el=>el.getAttribute('data-tree-edge')).sort();
const nodes=a=>tree(a).querySelectorAll('g[data-package-node]');
const action=(a,name)=>nodes(a).find(el=>el.getAttribute('data-package-node')===name);
const mode=(a,value)=>a.ids.get('edge-modes').querySelectorAll('button').find(b=>b.dataset.edges===value).click();
assert.equal(tree(app).hidden,false);
assert.equal(app.ids.get('dependency-browser').hidden,true);
assert.equal(app.run('ui.edgeMode'),'all','arrows must be visible immediately without a selection');
assert.equal(nodes(app).length,3);
assert.equal(pairs(app).length,4);
assert.equal(tree(app).querySelectorAll('polygon[data-tree-arrow]').length,4,'every directed dependency has a target arrow');
assert.ok(tree(app).querySelectorAll('path[data-tree-hierarchy]').length>=3);
const original=app.run('JSON.stringify([work,view,sccs,currentAcd,ops])');
const positions=()=>JSON.stringify(nodes(app).map(n=>[n.getAttribute('data-package-node'),n.getAttribute('transform')]));
const before=positions();
action(app,'A').click();
assert.equal(app.run('ui.diagram'),'overview','selecting a package keeps the graphical tree');
assert.equal(app.run('ui.edgeMode'),'both','selecting a reference focuses its arrows; All stays available explicitly');
assert.equal(tree(app).hidden,false);
mode(app,'both');const both=pairs(app);
mode(app,'incoming');const incoming=pairs(app);
mode(app,'outgoing');const outgoing=pairs(app);
assert.equal(incoming.length,2);assert.equal(outgoing.length,1);
assert.deepEqual([...new Set([...incoming,...outgoing])].sort(),both);
assert.equal(positions(),before,'filters and selection preserve tree positions');
mode(app,'all');
action(app,'B').click();
assert.equal(app.run('ui.edgeMode'),'all','an explicitly chosen direction mode is preserved on selection');
const selected=tree(app).querySelectorAll('g[data-tree-edge]')[0];
selected.click();assert.equal(app.run('ui.selection.kind'),'edge');
assert.match(app.ids.get('sidebar').textContent,/import references/);
assert.match(selected.querySelector('title').textContent,/→/);
assert.equal(tree(app).querySelectorAll('img').length,0);
assert.equal(app.run('JSON.stringify([work,view,sccs,currentAcd,ops])'),original);
action(app,'A').dispatch('dblclick');
assert.equal(app.run('ui.diagram'),'overview');
assert.ok(app.ids.get('breadcrumbs').textContent.includes('A'));
assert.ok(nodes(app).some(n=>n.getAttribute('data-package-node')==='A/a.ts'));
mode(app,'both');
const expected=JSON.parse(app.run("JSON.stringify(view.edges.filter(e=>dependencyMatchesSelection(e.from,e.to)&&displayedGraphNodes().some(n=>n.id===e.from)&&displayedGraphNodes().some(n=>n.id===e.to)).map(e=>e.from+' '+e.to).sort())"));
assert.deepEqual(pairs(app),expected,'opening a package retains external cycle return paths');
app.click('toggle-cycles');assert.deepEqual(pairs(app),expected,'package-level cycle context stays in Cycles only');
app.click('diagram-dependencies');assert.equal(tree(app).hidden,true);
app.click('diagram-overview');assert.equal(tree(app).hidden,false);
assert.equal(app.run('ui.selection.kind'),'node','changing presentation preserves the package reference');
const offline=launch(fixture,{library:false});
assert.equal(tree(offline).hidden,false);assert.equal(pairs(offline).length,4,'the SVG package tree works without the remote canvas library');
action(offline,'B').dispatch('keydown',{key:'Enter'});assert.equal(offline.run('ui.selection.name'),'B');
action(offline,'B').focus();
action(offline,'B').dispatch('keydown',{key:'ArrowRight'});assert.ok(nodes(offline).some(n=>n.getAttribute('data-package-node')==='B/b.ts'));
assert.equal(offline.document.activeElement.getAttribute('data-tree-source'),'3','opening a package with the keyboard retains focus on its context row');
assert.ok(tree(offline).querySelectorAll('g[data-tree-source]').includes(offline.document.activeElement),'focus belongs to the rebuilt tree, not a detached element');
const tooltipTarget=action(app,'A/a.ts');tooltipTarget.dispatch('pointerenter',{clientX:100,clientY:140});
assert.equal(app.ids.get('graph-context-tooltip').hidden,false);
assert.match(app.ids.get('graph-context-tooltip').textContent,/A\/a\.ts/);
tooltipTarget.dispatch('pointerleave');assert.equal(app.ids.get('graph-context-tooltip').hidden,true);
tree(app).scrollTop=500;tree(app).scrollLeft=200;
tree(app).querySelectorAll('button').find(b=>b.textContent==='Reset tree').click();
assert.equal(tree(app).scrollTop,0);assert.equal(tree(app).scrollLeft,0);
assert.equal(app.run('ui.edgeMode'),'all');assert.equal(pairs(app).length,4);
const double=launch(fixture);
action(double,'A').dispatch('click',{timeStamp:1000});
action(double,'A').dispatch('click',{timeStamp:1200});
assert.ok(nodes(double).some(n=>n.getAttribute('data-package-node')==='A/a.ts'),'two clicks open a package even when selection repaints its SVG element');
const many=launch({...fixture,nodes:Array.from({length:120},(_,id)=>node(id,'package-'+id)),edges:[]});
assert.equal(nodes(many).length,120,'a tree keeps every visible package, with scrolling instead of card pagination');
assert.ok(Number(tree(many).querySelector('svg').getAttribute('height'))>600,'the tree retains readable row heights rather than auto-fitting everything');
const dense=launch({...fixture,nodes:Array.from({length:120},(_,id)=>node(id,'package-'+id)),edges:Array.from({length:119},(_,i)=>edge(0,i+1))});
const first=nodes(dense)[0],centerX=Number(first.getAttribute('transform').match(/translate\(([^ ]+)/)[1]);
const halfWidth=Number(first.querySelector('rect[data-tree-row]').getAttribute('width'))/2,left=tree(dense).scrollLeft||0;
assert.ok(centerX-halfWidth>=left&&centerX+halfWidth<=left+tree(dense).getBoundingClientRect().width,'the compact label column stays visible in the initial viewport');
console.log('Package tree: arrows by default, stable filters, evidence, external cycles, drill-down, keyboard, offline rendering and scrolling passed');
