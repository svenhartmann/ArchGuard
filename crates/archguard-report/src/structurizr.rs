//! Structurizr DSL (C4, ADR 0013): one software system whose containers
//! are the services of the static service topology, datastores outside it
//! as external systems, and — for one selected service — its packages as
//! components. Relations carry their protocol and configuration evidence;
//! nothing here is measured traffic.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use archguard_core::{Service, ServiceDependencyKind, ServiceEvidence, ServiceTopology};

/// The packages of one service, as components of its container.
pub struct C4Components<'a> {
    /// The service id (`ServiceTopology::services[].id`).
    pub service: &'a str,
    /// Package (module) names, in output order.
    pub modules: Vec<String>,
    /// Source connections `(from, to, references)` between `modules`.
    pub relations: Vec<(String, String, u64)>,
}

/// Evidence entries shown per relation; the rest is counted.
const EVIDENCE: usize = 3;

/// Element ids by service or datastore id.
type Ids = BTreeMap<String, String>;

/// The workspace of `system`. Identifiers are generated (`c0`, `x0`,
/// `p0`), so any service or package name is safe.
#[tracing::instrument(skip_all)]
pub fn to_structurizr(
    system: &str,
    t: &ServiceTopology,
    components: Option<&C4Components<'_>>,
) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "workspace {} {} {{\n    model {{\n        system = softwareSystem {} {} {{",
        q(system),
        q(
            "Generated by ArchGuard from static configuration and source evidence; no measured traffic."
        ),
        q(system),
        q("Containers are the services declared in deployment configuration."),
    );
    let mut ids = Ids::new();
    let mut component_relations = String::new();
    let repeated = repeated(t.services.iter().map(|s| s.name.as_str()));
    for (i, s) in t.services.iter().enumerate() {
        let id = format!("c{i}");
        // The DSL refuses two elements of one name: then the id names it.
        let name = if repeated.contains(s.name.as_str()) {
            &s.id
        } else {
            &s.name
        };
        let _ = write!(out, "            {id} = {}", container(t, s, name));
        if let Some(c) = components.filter(|c| c.service == s.id) {
            component_relations = write_components(&mut out, c);
        }
        out.push('\n');
        ids.insert(s.id.clone(), id);
    }
    out.push_str("        }\n");
    external_datastores(&mut out, t, &mut ids);
    for ((a, b, label), (technology, evidence)) in relations(t, &ids) {
        let _ = write!(out, "        {a} -> {b} {} {}", q(&label), q(technology));
        out.push_str(&properties(&evidence));
    }
    out.push_str(&component_relations);
    out.push_str("    }\n    views {\n        container system \"Containers\" {\n            include *\n            autolayout lr\n        }\n");
    if let Some(id) = components.and_then(|c| ids.get(c.service)) {
        let _ = writeln!(
            out,
            "        component {id} \"Components\" {{\n            include *\n            autolayout lr\n        }}"
        );
    }
    out.push_str("        styles {\n            element \"Database\" {\n                shape cylinder\n            }\n            element \"External\" {\n                background #999999\n            }\n        }\n    }\n}\n");
    out
}

/// `container name description technology tags` of service `s`; the
/// technology is the datastore engine or the project runtime, if known.
fn container(t: &ServiceTopology, s: &Service, name: &str) -> String {
    let store = t
        .datastores
        .nodes
        .iter()
        .find(|d| d.service.as_deref() == Some(&s.id));
    let project = s
        .project
        .as_ref()
        .and_then(|p| t.projects.iter().find(|x| &x.id == p));
    let technology = store
        .and_then(|d| d.engine.clone())
        .or_else(|| project.map(|p| p.runtime.clone().unwrap_or_else(|| p.ecosystem.clone())))
        .unwrap_or_default();
    let tags = if store.is_some() { "Database" } else { "" };
    format!(
        "container {} {} {} {}",
        q(name),
        q(&s.compose_file),
        q(&technology),
        q(tags)
    )
}

/// The component block of a container; returns the relations between
/// the components, written after all elements.
fn write_components(out: &mut String, c: &C4Components<'_>) -> String {
    out.push_str(" {\n");
    let mut names = BTreeMap::new();
    for (j, m) in c.modules.iter().enumerate() {
        let pid = format!("p{j}");
        let _ = writeln!(out, "                {pid} = component {}", q(m));
        names.insert(m.as_str(), pid);
    }
    out.push_str("            }");
    let mut relations = String::new();
    for (from, to, n) in &c.relations {
        if let (Some(a), Some(b)) = (names.get(from.as_str()), names.get(to.as_str())) {
            let _ = writeln!(
                relations,
                "        {a} -> {b} {} {}",
                q(&format!(
                    "{n} source reference{}",
                    if *n == 1 { "" } else { "s" }
                )),
                q("import")
            );
        }
    }
    relations
}

/// Datastores without a service of their own are outside the system.
fn external_datastores(out: &mut String, t: &ServiceTopology, ids: &mut Ids) {
    let external: Vec<_> = t
        .datastores
        .nodes
        .iter()
        .filter(|d| d.service.is_none())
        .collect();
    let repeated = repeated(external.iter().filter_map(|d| d.host.as_deref()));
    for (i, d) in external.into_iter().enumerate() {
        let id = format!("x{i}");
        let name = match (&d.host, d.port) {
            (Some(h), Some(p)) if repeated.contains(h.as_str()) => format!("{h}:{p}"),
            (Some(h), _) if !repeated.contains(h.as_str()) => h.clone(),
            _ => d.id.clone(),
        };
        let mut what = "Datastore outside the configuration".to_owned();
        if let Some(e) = &d.engine {
            let _ = write!(what, ": {e}");
        }
        if let Some(p) = d.port {
            let _ = write!(what, ", port {p}");
        }
        let _ = writeln!(
            out,
            "        {id} = softwareSystem {} {} {}",
            q(&name),
            q(&what),
            q("External,Database")
        );
        ids.insert(d.id.clone(), id);
    }
}

type Relations<'t> = BTreeMap<(String, String, String), (&'t str, Vec<&'t ServiceEvidence>)>;

/// One relation per (from, to, label), since the DSL refuses duplicates;
/// the evidence of merged links is kept together.
fn relations<'t>(t: &'t ServiceTopology, ids: &Ids) -> Relations<'t> {
    let mut relations = Relations::new();
    for d in &t.dependencies {
        let (Some(a), Some(b)) = (ids.get(&d.from), ids.get(&d.to)) else {
            continue;
        };
        let (label, technology) = kind(d.kind);
        relations
            .entry((a.clone(), b.clone(), label.into()))
            .or_insert((technology, Vec::new()))
            .1
            .extend(&d.evidence);
    }
    for u in &t.datastores.usages {
        let (Some(a), Some(b)) = (ids.get(&u.service), ids.get(&u.datastore)) else {
            continue;
        };
        let label = match &u.database {
            Some(db) => format!("uses datastore, database {db}"),
            None => "uses datastore".into(),
        };
        let engine = t
            .datastores
            .nodes
            .iter()
            .find(|d| d.id == u.datastore)
            .and_then(|d| d.engine.as_deref())
            .unwrap_or("");
        relations
            .entry((a.clone(), b.clone(), label))
            .or_insert((engine, Vec::new()))
            .1
            .extend(&u.evidence);
    }
    relations
}

/// The end of a relation line: an `evidence` property, if there is any.
fn properties(evidence: &[&ServiceEvidence]) -> String {
    if evidence.is_empty() {
        return "\n".into();
    }
    // Merged links repeat the same evidence.
    let mut cited: Vec<String> = evidence.iter().map(|e| cite(e)).collect();
    cited.sort();
    cited.dedup();
    let more = cited.len().saturating_sub(EVIDENCE);
    let mut shown: Vec<String> = cited.into_iter().take(EVIDENCE).collect();
    if more > 0 {
        shown.push(format!("+{more} more"));
    }
    format!(
        " {{\n            properties {{\n                \"evidence\" {}\n            }}\n        }}\n",
        q(&shown.join("; "))
    )
}

/// Description and technology of a service link.
fn kind(k: ServiceDependencyKind) -> (&'static str, &'static str) {
    match k {
        ServiceDependencyKind::Startup => ("starts after", "depends_on"),
        ServiceDependencyKind::ConfiguredHttp => ("HTTP, configured", "HTTP"),
        ServiceDependencyKind::HttpCall => ("HTTP call", "HTTP"),
        ServiceDependencyKind::GrpcCall => ("gRPC call", "gRPC"),
        ServiceDependencyKind::Event => ("event", "messaging"),
        ServiceDependencyKind::ConfiguredReference => ("configured reference", ""),
    }
}

/// The names that occur more than once.
fn repeated<'a>(names: impl Iterator<Item = &'a str>) -> BTreeSet<&'a str> {
    let mut seen = BTreeSet::new();
    names.filter(|n| !seen.insert(*n)).collect()
}

fn cite(e: &ServiceEvidence) -> String {
    match e.line {
        Some(l) => format!("{}:{l} {}", e.file, e.pointer),
        None => format!("{} {}", e.file, e.pointer),
    }
}

/// A DSL string: quotes and backslashes escaped, line breaks flattened.
fn q(s: &str) -> String {
    let flat: String = s
        .chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect();
    format!("\"{}\"", flat.replace('\\', "\\\\").replace('"', "\\\""))
}

#[cfg(test)]
mod tests {
    use super::*;
    use archguard_core::{
        Datastore, DatastoreUsage, Service, ServiceDatastores, ServiceDependency,
    };

    fn service(id: &str) -> Service {
        Service {
            id: format!("compose.yaml::{id}"),
            name: id.into(),
            compose_file: "compose.yaml".into(),
            build_context: Some(id.into()),
            networks: vec![],
            profiles: vec![],
            project: None,
        }
    }

    fn evidence(line: u32) -> ServiceEvidence {
        ServiceEvidence {
            file: "compose.yaml".into(),
            pointer: "/services/orders/environment/BILLING_API".into(),
            line: Some(line),
            description: String::new(),
        }
    }

    fn topology() -> ServiceTopology {
        ServiceTopology {
            schema_version: 1,
            root: "/x".into(),
            monorepo: false,
            monorepo_reason: String::new(),
            compose_files: vec!["compose.yaml".into()],
            services: vec![service("orders"), service("billing"), service("db")],
            projects: vec![],
            dependencies: vec![ServiceDependency {
                from: "compose.yaml::orders".into(),
                to: "compose.yaml::billing".into(),
                kind: ServiceDependencyKind::ConfiguredHttp,
                evidence: vec![evidence(5)],
            }],
            cycles: vec![],
            diagnostics: vec![],
            datastores: ServiceDatastores {
                nodes: vec![
                    Datastore {
                        id: "compose.yaml::db".into(),
                        engine: Some("postgresql".into()),
                        service: Some("compose.yaml::db".into()),
                        host: None,
                        port: None,
                        evidence: vec![],
                    },
                    Datastore {
                        id: "external:cache:6379".into(),
                        engine: Some("redis".into()),
                        service: None,
                        host: Some("cache".into()),
                        port: Some(6379),
                        evidence: vec![],
                    },
                ],
                usages: vec![
                    DatastoreUsage {
                        service: "compose.yaml::orders".into(),
                        datastore: "compose.yaml::db".into(),
                        database: Some("orders".into()),
                        tables: vec![],
                        evidence: vec![evidence(7)],
                    },
                    DatastoreUsage {
                        service: "compose.yaml::billing".into(),
                        datastore: "external:cache:6379".into(),
                        database: None,
                        tables: vec![],
                        evidence: vec![],
                    },
                ],
                shared: vec![],
                tables: vec![],
                note: String::new(),
            },
            complete: true,
            traces: vec![],
            routes: vec![],
            resilience: vec![],
        }
    }

    #[test]
    fn services_become_containers_with_protocol_and_evidence() {
        let dsl = to_structurizr("shop \"x\"", &topology(), None);
        assert!(dsl.starts_with("workspace \"shop \\\"x\\\"\""), "{dsl}");
        assert!(
            dsl.contains("c0 = container \"orders\" \"compose.yaml\" \"\" \"\""),
            "{dsl}"
        );
        assert!(
            dsl.contains("c2 = container \"db\" \"compose.yaml\" \"postgresql\" \"Database\""),
            "{dsl}"
        );
        assert!(
            dsl.contains("x0 = softwareSystem \"cache\" \"Datastore outside the configuration: redis, port 6379\" \"External,Database\""),
            "{dsl}"
        );
        assert!(
            dsl.contains("c0 -> c1 \"HTTP, configured\" \"HTTP\" {"),
            "{dsl}"
        );
        assert!(
            dsl.contains(
                "\"evidence\" \"compose.yaml:5 /services/orders/environment/BILLING_API\""
            ),
            "{dsl}"
        );
        assert!(
            dsl.contains("c0 -> c2 \"uses datastore, database orders\" \"postgresql\""),
            "{dsl}"
        );
        assert!(
            dsl.contains("c1 -> x0 \"uses datastore\" \"redis\"\n"),
            "{dsl}"
        );
        assert!(dsl.contains("container system \"Containers\""), "{dsl}");
        assert!(!dsl.contains("component "), "{dsl}");
        assert_eq!(
            dsl.matches('{').count(),
            dsl.matches('}').count(),
            "balanced blocks: {dsl}"
        );
    }

    #[test]
    fn a_selected_service_lists_its_packages_as_components() {
        let c = C4Components {
            service: "compose.yaml::orders",
            modules: vec!["orders/api".into(), "orders/domain".into()],
            relations: vec![
                ("orders/api".into(), "orders/domain".into(), 4),
                ("orders/api".into(), "billing/x".into(), 1),
            ],
        };
        let dsl = to_structurizr("shop", &topology(), Some(&c));
        assert!(
            dsl.contains("c0 = container \"orders\" \"compose.yaml\" \"\" \"\" {\n                p0 = component \"orders/api\"\n                p1 = component \"orders/domain\"\n            }"),
            "{dsl}"
        );
        assert!(
            dsl.contains("p0 -> p1 \"4 source references\" \"import\""),
            "{dsl}"
        );
        assert!(!dsl.contains("billing/x"), "{dsl}");
        assert!(dsl.contains("component c0 \"Components\""), "{dsl}");
        assert_eq!(dsl.matches('{').count(), dsl.matches('}').count(), "{dsl}");
    }

    #[test]
    fn repeated_names_fall_back_to_ids_and_evidence_is_shown_once() {
        let mut t = topology();
        let mut other = service("orders");
        other.id = "shop/compose.yaml::orders".into();
        other.compose_file = "shop/compose.yaml".into();
        t.services.push(other);
        let mut cache = t.datastores.nodes[1].clone();
        cache.id = "external:cache:6380".into();
        cache.port = Some(6380);
        t.datastores.nodes.push(cache);
        let link = t.dependencies[0].clone();
        t.dependencies.push(link);
        let dsl = to_structurizr("shop", &t, None);
        assert!(
            dsl.contains("c0 = container \"compose.yaml::orders\""),
            "{dsl}"
        );
        assert!(
            dsl.contains("c3 = container \"shop/compose.yaml::orders\""),
            "{dsl}"
        );
        assert!(dsl.contains("c1 = container \"billing\""), "{dsl}");
        assert!(dsl.contains("x0 = softwareSystem \"cache:6379\""), "{dsl}");
        assert!(dsl.contains("x1 = softwareSystem \"cache:6380\""), "{dsl}");
        assert!(
            dsl.contains(
                "\"evidence\" \"compose.yaml:5 /services/orders/environment/BILLING_API\"\n"
            ),
            "{dsl}"
        );
    }
}
